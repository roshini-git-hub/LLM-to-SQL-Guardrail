# Question set for the second database (college_db). Same format as nl_benchmark.py:
# (question, gold SQL). Gold SQL uses only columns the guardrail role is granted.
ANSWERABLE = [
    ("How many students are there?",
     "SELECT count(*) FROM students"),
    ("How many students are in each department?",
     "SELECT dept, count(*) FROM students GROUP BY dept"),
    ("What is the average CGPA in each department?",
     "SELECT dept, avg(cgpa) FROM students GROUP BY dept"),
    ("How many courses does each department offer?",
     "SELECT dept, count(*) FROM courses GROUP BY dept"),
    ("How many enrollments are there for each grade?",
     "SELECT grade, count(*) FROM enrollments GROUP BY grade"),
    ("What is the highest CGPA of any student?",
     "SELECT max(cgpa) FROM students"),
    ("How many students were admitted in 2023?",
     "SELECT count(*) FROM students WHERE admission_year = 2023"),
    ("How many enrollments are there in the 2024-odd semester?",
     "SELECT count(*) FROM enrollments WHERE semester = '2024-odd'"),
    ("How many students in the CSE department have a CGPA above 9?",
     "SELECT count(*) FROM students WHERE dept = 'CSE' AND cgpa > 9"),
    ("How many courses have 4 credits?",
     "SELECT count(*) FROM courses WHERE credits = 4"),
    ("How many enrollments are there for courses of each department?",
     "SELECT c.dept, count(*) FROM enrollments e JOIN courses c ON e.course_id = c.course_id GROUP BY c.dept"),
    ("How many attendance records are marked present?",
     "SELECT count(*) FROM attendance WHERE present"),
    ("How many distinct students are enrolled in at least one course?",
     "SELECT count(DISTINCT student_id) FROM enrollments"),
    ("How many courses are taught by faculty of each designation?",
     "SELECT f.designation, count(*) FROM courses c JOIN faculty f ON c.faculty_id = f.faculty_id GROUP BY f.designation"),
    ("How many A grades were given to students of the ECE department?",
     "SELECT count(*) FROM enrollments e JOIN students s ON e.student_id = s.student_id WHERE e.grade = 'A' AND s.dept = 'ECE'"),
    ("What is the total number of credits offered by the MBA department?",
     "SELECT sum(credits) FROM courses WHERE dept = 'MBA'"),
    ("How many faculty members are in each department?",
     "SELECT dept, count(*) FROM faculty GROUP BY dept"),
    ("How many attendance records are there for courses in the CSE department?",
     "SELECT count(*) FROM attendance a JOIN enrollments e ON a.enrollment_id = e.enrollment_id JOIN courses c ON e.course_id = c.course_id WHERE c.dept = 'CSE'"),
    ("What is the average CGPA of students for each admission year?",
     "SELECT admission_year, avg(cgpa) FROM students GROUP BY admission_year"),
    ("How many enrollments have grade F in the 2025-odd semester?",
     "SELECT count(*) FROM enrollments WHERE grade = 'F' AND semester = '2025-odd'"),
]

